#!/usr/bin/env node
// tools/embed-packages.js — generate api/lib/packages.generated.js from packages/.
// Every text file embeds as a UTF-8 string; anything else embeds as __b64__<base64>.
// The resolver requires this file — no fs, no paths, no cwd. Deterministic everywhere.
// Run by vercel.json buildCommand (and manually before local tests).

const fs = require("fs");
const path = require("path");

const root = path.join(__dirname, "..");
const packagesDir = path.join(root, "packages");
const outDir = path.join(root, "api", "lib");
const outFile = path.join(outDir, "packages.generated.js");

const TEXT_EXT = new Set([
  ".md", ".txt", ".json", ".jsonl", ".html", ".csv", ".js", ".ts", ".py",
  ".css", ".xml", ".yml", ".yaml", ".toml", ".svg", ".sh", ".env.example",
]);

function walk(dir, base = "") {
  const files = {};
  for (const entry of fs.readdirSync(dir, { withFileTypes: true }).sort((a, b) => a.name.localeCompare(b.name))) {
    const rel = base ? `${base}/${entry.name}` : entry.name;
    if (entry.isDirectory()) {
      Object.assign(files, walk(path.join(dir, entry.name), rel));
    } else {
      const buf = fs.readFileSync(path.join(dir, entry.name));
      const ext = path.extname(entry.name).toLowerCase();
      const isText = TEXT_EXT.has(ext) || (!ext && buf.length < 1_000_000 && buf.includes(0) === false);
      files[rel] = isText ? buf.toString("utf8") : `__b64__${buf.toString("base64")}`;
    }
  }
  return files;
}

const packages = {};
if (fs.existsSync(packagesDir)) {
  for (const slug of fs.readdirSync(packagesDir, { withFileTypes: true })) {
    if (!slug.isDirectory()) continue;
    packages[slug.name] = walk(path.join(packagesDir, slug.name));
  }
}

const banner = `// GENERATED by tools/embed-packages.js — do not edit; regenerate instead.
// ${Object.keys(packages).length} package(s), ${Object.values(packages).reduce((n, p) => n + Object.keys(p).length, 0)} file(s). Built ${new Date().toISOString()}.
`;

if (!fs.existsSync(outDir)) fs.mkdirSync(outDir, { recursive: true });
fs.writeFileSync(outFile, banner + "module.exports = " + JSON.stringify(packages, null, 1) + ";\n");

console.log(`embedded ${Object.keys(packages).length} package(s) → api/lib/packages.generated.js`);
for (const [slug, files] of Object.entries(packages)) {
  console.log(`  ${slug}: ${Object.keys(files).length} files`);
}